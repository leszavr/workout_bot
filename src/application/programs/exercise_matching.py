"""Сопоставление свободного текста пользователя с упражнениями каталога.

Пользователь пишет, чего не хочет, своими словами: «выпады», «бег», «жим лёжа».
В каталоге эти упражнения называются иначе — «Выпад со штангой», «Ходьба
выпадами со штангой», «Бег на беговой дорожке». Сравнение строк целиком здесь не
работает: из 11 упражнений с выпадами точному совпадению «выпады» отвечает одно,
а остальные десять попали бы в программу вопреки прямому отказу пользователя.

Правило сопоставления: все значимые слова запроса должны присутствовать в
названии упражнения, слова сравниваются по префиксу. Префикс закрывает
расхождение числа и падежа («выпады» ↔ «выпад», «приседания» ↔ «присед») без
словаря словоформ и без внешних зависимостей. Проверено на каталоге из 873
упражнений: «выпады» → 11, «приседания» → 55, «жим лёжа» → 20, «бег» → 4.

Короткие слова из запроса не отбрасываются. Соблазн отбросить есть — «на», «up»
дают совпадения где угодно, — но отбрасывание расширяет совпадение: у запроса
«Exercise A» осталось бы одно слово «exercise», и под него попало бы всё. Вместо
длины используется список служебных слов: он ограничивает совпадение, а не
расширяет его.

Сопоставление намеренно широкое в остальном. Ошибка в сторону лишнего исключения
стоит администратору меньше, чем упражнение, от которого человек прямо отказался:
во втором случае он получает программу, которую не будет выполнять, а в первом —
чуть меньший выбор в пуле. Пул при этом не может «схлопнуться» незаметно:
слишком маленький пул останавливает генерацию с явной ошибкой.
"""
from __future__ import annotations

import re

# Служебные слова: в названиях упражнений и в ответах они встречаются почти
# всегда, и совпадение по ним ничего не значит. Список ограничивает совпадение,
# поэтому пополнять его безопасно — в отличие от фильтра по длине слова.
STOP_WORDS = frozenset(
    {
        # предлоги и союзы
        "с", "со", "на", "в", "во", "и", "или", "для", "без", "от", "до", "по",
        "из", "за", "над", "под", "при", "к", "у", "о", "об",
        # частицы и местоимения: пользователь пишет фразой, а не одним словом
        "не", "ни", "но", "а", "же", "бы", "ли", "то", "что", "как", "я", "мне",
        "это", "их", "его", "её", "ее", "все", "всё", "вообще", "хочу", "люблю",
        "могу", "нельзя", "нет",
        # английские служебные
        "the", "with", "of", "to", "and", "or", "a", "an", "for", "in", "on",
        "at", "by", "from", "no", "not",
    }
)

# Длина сравниваемого префикса. Пять символов — компромисс, найденный на
# реальном каталоге: «присед» и «приседания» совпадают, а «жим» и «жимовой»
# не склеиваются с посторонними словами.
STEM_LENGTH = 5

# Ответы, которыми пользователь сообщает «ничего нет». Исключать по ним нельзя:
# после отбрасывания служебных слов от такой фразы не остаётся ничего значимого,
# но проверка явная — чтобы поведение не зависело от состава STOP_WORDS.
NOISE_ANSWERS = frozenset(
    {
        "нет", "ничего", "не знаю", "никаких", "none", "no", "-", "—", "–",
        "нет ограничений", "нет предпочтений", "все нравятся", "всё нравится",
    }
)


def _stems(text: str) -> set[str]:
    """Значимые слова текста, усечённые до префикса."""
    lowered = text.lower().replace("ё", "е")
    words = re.findall(r"[a-zа-я0-9]+", lowered)
    return {word[:STEM_LENGTH] for word in words if word not in STOP_WORDS}


def normalize_unwanted(phrases: list[str]) -> list[set[str]]:
    """Готовит запросы пользователя к сопоставлению.

    Возвращает по одному набору основ на каждую осмысленную фразу. Фразы-пустышки
    («нет», «ничего») отбрасываются: по ним исключать нельзя.
    """
    prepared: list[set[str]] = []
    for phrase in phrases:
        cleaned = phrase.strip()
        if not cleaned or cleaned.lower().replace("ё", "е") in NOISE_ANSWERS:
            continue
        stems = _stems(cleaned)
        if stems:
            prepared.append(stems)
    return prepared


def matches_unwanted(
    *, name: str, name_ru: str | None, aliases: list[str], unwanted: list[set[str]]
) -> bool:
    """Отвечает ли упражнение хотя бы одному запросу пользователя.

    Сравниваются все известные названия упражнения: каталог англоязычный, а
    пользователь пишет по-русски, поэтому русское название и синонимы обязательны
    — без них «выпады» не нашли бы ни одного упражнения.
    """
    if not unwanted:
        return False
    exercise_stems = _stems(name)
    if name_ru:
        exercise_stems |= _stems(name_ru)
    for alias in aliases:
        exercise_stems |= _stems(alias)
    return any(query <= exercise_stems for query in unwanted)
