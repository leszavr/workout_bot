# «При развитии одной мышечной группы рекомендуется выполнять одно главное
# упражнение и 2-3 дополнительных или вспомогательных» — то есть на группу мышц
# приходится 3–4 упражнения. Отсюда следует, сколько групп разумно брать в один
# день при известном числе упражнений.
EXERCISES_PER_MUSCLE_GROUP = (3, 4)

# «Чем меньше количество упражнений на одну группу мышц, тем больше должно быть
# подходов и наоборот» — обратная зависимость объёма от разнообразия. В расчёте
# занятия это выражено тем, что подходы подбираются после числа упражнений.
