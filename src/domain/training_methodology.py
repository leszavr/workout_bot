# --- Категории упражнений (раздел 1.2) ------------------------------------------
#
# Методика делит упражнения на четыре категории по нагрузке на нервную систему.
# В каталоге такого поля нет, но есть `mechanic` (compound/isolation) и
# `equipment`, и этого достаточно, чтобы отличить главные упражнения от
# вспомогательных: главные — многосуставные со свободным весом, вспомогательные —
# изолирующие и тренажёрные.

CATEGORY_MAIN = "main"
CATEGORY_SECONDARY = "secondary"
CATEGORY_ACCESSORY = "accessory"

CATEGORY_TITLES = {
    CATEGORY_MAIN: "базовое",
    CATEGORY_SECONDARY: "дополнительное",
    CATEGORY_ACCESSORY: "вспомогательное",
}

# Порядок категорий внутри тренировки. Методика (раздел 1.3): «первым всегда
# выполняется блок упражнений, который сильнее нагружает центральную нервную
# систему», то есть базовые упражнения идут до вспомогательных. Обратный порядок
# означает, что базовое движение выполняется уже уставшим — это и хуже по
# результату, и опаснее по технике.
CATEGORY_ORDER = (CATEGORY_MAIN, CATEGORY_SECONDARY, CATEGORY_ACCESSORY)

# Свободный вес: с ним выполняются главные упражнения методики. Тренажёры и
# блоки упрощают движение и снижают нагрузку на нервную систему, поэтому
# относятся к вспомогательным независимо от механики.
FREE_WEIGHT_EQUIPMENT = frozenset(
    {"barbell", "dumbbell", "kettlebells", "e-z curl bar", "body only", "other"}
)

# Тренажёрное и блочное оборудование: признак вспомогательного упражнения.
MACHINE_EQUIPMENT = frozenset({"machine", "cable"})


def classify_category(exercise: Exercise) -> str:
    """Категория упражнения по методике.

    Правило соответствия каталогу:
    - многосуставное (`compound`) со свободным весом → базовое;
    - многосуставное на тренажёре или блоке → дополнительное;
    - изолирующее → вспомогательное.

    Соответствие приблизительное: в каталоге нет разделения «базовое /
    дополнительное» в терминах методики, и восстановить его точно по атрибутам
    нельзя. Для порядка упражнений внутри тренировки этой точности достаточно —
    важно, чтобы тяжёлое многосуставное движение шло раньше изолирующего.
    """
    equipment = set(exercise.equipment)
    if exercise.mechanic == "isolation":
        return CATEGORY_ACCESSORY
    if exercise.mechanic == "compound":
        if equipment & MACHINE_EQUIPMENT:
            return CATEGORY_SECONDARY
        if equipment & FREE_WEIGHT_EQUIPMENT or not equipment:
            return CATEGORY_MAIN
        return CATEGORY_SECONDARY
    # Механика не указана (кардио и часть упражнений каталога): к базовым такое
    # упражнение отнести нельзя, а исключать из тренировки незачем.
    return CATEGORY_ACCESSORY


def category_rank(exercise: Exercise) -> int:
    """Позиция категории в порядке выполнения. Меньше — раньше."""
    return CATEGORY_ORDER.index(classify_category(exercise))


# --- Нормативы по целям (раздел 1.2) --------------------------------------------


@dataclass(frozen=True)
class GoalNorms:
    """Методические нормативы для одной цели.

    Диапазоны, а не точные значения: методика задаёт границы, внутри которых
    выбор зависит от числа упражнений на группу мышц и подготовленности. Внутри
    диапазона выбор делает расчёт занятия (`session_planning`) — он подбирает
    подходы так, чтобы занятие уложилось в заявленное время.
    """

    sets_min: int
    sets_max: int
    reps_min: int
    reps_max: int
    rest_min_seconds: int
    rest_max_seconds: int
    # Как эта цель тренируется — формулировка для промпта и описания программы.
    approach: str

    @property
    def sets_default(self) -> int:
        return (self.sets_min + self.sets_max) // 2

    @property
    def rest_default_seconds(self) -> int:
        return (self.rest_min_seconds + self.rest_max_seconds) // 2


# Цель → нормативы. Числа для силы, массы и выносливости взяты из методики
# напрямую; для остальных целей выведены из ближайшего методического аналога,
# потому что документ таких целей не рассматривает:
# - здоровье и форма → умеренный режим между массой и выносливостью;
# - возвращение к тренировкам → щадящий: меньше подходов, длиннее отдых.
GOAL_NORMS: dict[PrimaryGoal | None, GoalNorms] = {
    # Методика: 3–5 подходов, 4–8 повторений, 2–3 минуты отдыха.
    PrimaryGoal.STRENGTH: GoalNorms(
        3, 5, 4, 8, 120, 180,
        "максимальный вес, малое число повторений, полное восстановление между подходами",
    ),
    # Методика: 3–5 подходов, 8–12 повторений, 2–5 минут отдыха.
    PrimaryGoal.MUSCLE_GAIN: GoalNorms(
        3, 5, 8, 12, 120, 300,
        "средний диапазон повторений, умеренный вес, отдых до восстановления",
    ),
    # Методика: 3–6 подходов, 20 и более повторений, 30–60 секунд отдыха.
    # Круговая схема — рекомендация методики для этой цели.
    PrimaryGoal.WEIGHT_LOSS: GoalNorms(
        3, 6, 15, 25, 30, 60,
        "небольшой вес, много повторений, короткий отдых; уместна круговая схема",
    ),
    PrimaryGoal.ENDURANCE: GoalNorms(
        3, 6, 20, 30, 30, 60,
        "высокое число повторений, минимальные паузы",
    ),
    PrimaryGoal.HEALTH_FITNESS: GoalNorms(
        2, 4, 10, 15, 60, 120,
        "умеренная нагрузка, комфортный отдых, акцент на технику",
    ),
    PrimaryGoal.RETURN_TO_TRAINING: GoalNorms(
        2, 3, 10, 12, 90, 150,
        "щадящий режим: мало подходов, длинный отдых, приоритет восстановлению",
    ),
    PrimaryGoal.OTHER: GoalNorms(
        3, 4, 10, 12, 60, 120, "умеренная нагрузка общего характера"
    ),
    None: GoalNorms(3, 4, 10, 12, 60, 120, "умеренная нагрузка общего характера"),
}

# Цели, для которых длительное занятие противоречит самой цели. Методика об
# эктоморфе: «тренировка должна быть достаточно интенсивной, но короткой, не
# более часа с учётом разминки и заминки». Для щадящих режимов это тем более
# верно: программа возвращения к тренировкам на два часа перестаёт быть
# программой возвращения.
GOAL_MAX_SESSION_MINUTES: dict[PrimaryGoal | None, int] = {
    PrimaryGoal.RETURN_TO_TRAINING: 60,
    PrimaryGoal.HEALTH_FITNESS: 75,
}

# Разминка и заминка: 10–15 минут на обе (методика, раздел 1.1). Растяжка и
# мобилизация относятся именно сюда, а не к основной работе, поэтому в пул
# упражнений они не попадают (см. `filtering`).
WARMUP_COOLDOWN_MINUTES = (10, 15)


def goal_norms(goal: PrimaryGoal | None) -> GoalNorms:
    return GOAL_NORMS.get(goal, GOAL_NORMS[None])


def max_session_minutes(goal: PrimaryGoal | None) -> int | None:
    """Предельная длительность занятия для цели. None — ограничения нет."""
    return GOAL_MAX_SESSION_MINUTES.get(goal)


